# Day 3 - Python Operators

a = 10
b = 3

# Arithmetic Operators
print("Arithmetic Operators")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

# Comparison Operators
print("\nComparison Operators")
print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)

# Logical Operators
x = True
y = False

print("\nLogical Operators")
print("x and y:", x and y)
print("x or y:", x or y)
print("not x:", not x)

# Assignment Operators
number = 10

number += 5
print("\nAssignment Operator (+=):", number)

number *= 2
print("Assignment Operator (*=):", number)
